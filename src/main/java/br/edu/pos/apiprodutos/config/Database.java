import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class Database {

    private static final String URL =
            "jdbc:h2:file:./dados/produtos;AUTO_SERVER=TRUE";

    private static final String USUARIO = "sa";
    private static final String SENHA = "";

    public static Connection conectar() throws SQLException {

        return DriverManager.getConnection(
                URL,
                USUARIO,
                SENHA
        );
    }

    /**
     * Cria a tabela (banco novo) e migra o esquema (banco já existente).
     *
     * Estratégia de migração: CREATE TABLE IF NOT EXISTS não adiciona colunas
     * em tabelas que já existem, então depois dele rodamos um
     * ALTER TABLE ... ADD COLUMN IF NOT EXISTS, que é idempotente:
     *  - banco novo: a coluna já nasce no CREATE TABLE e o ALTER não faz nada;
     *  - banco antigo (sem estoque): o ALTER adiciona a coluna e os produtos
     *    já cadastrados ficam com estoque 0 (DEFAULT 0 NOT NULL);
     *  - reinício da API: ambos os comandos não fazem nada.
     * Assim nenhum dado existente é perdido e não é preciso apagar o banco.
     *
     * Uma constraint CHECK garante no próprio banco que o estoque nunca
     * fica negativo, mesmo se algum código futuro esquecer a regra.
     */
    public static void inicializar() {

        String criarTabela = """
                CREATE TABLE IF NOT EXISTS produtos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome VARCHAR(150) NOT NULL,
                    preco DOUBLE PRECISION NOT NULL,
                    quantidade_estoque INT DEFAULT 0 NOT NULL
                )
                """;

        String adicionarColuna = """
                ALTER TABLE produtos
                ADD COLUMN IF NOT EXISTS quantidade_estoque INT DEFAULT 0 NOT NULL
                """;

        String adicionarRegra = """
                ALTER TABLE produtos
                ADD CONSTRAINT IF NOT EXISTS ck_produtos_estoque_nao_negativo
                CHECK (quantidade_estoque >= 0)
                """;

        try (
                Connection conexao = conectar();
                Statement comando = conexao.createStatement()
        ) {

            comando.execute(criarTabela);
            comando.execute(adicionarColuna);
            comando.execute(adicionarRegra);

            System.out.println("Banco de dados inicializado!");

        } catch (SQLException erro) {

            throw new RuntimeException(
                    "Erro ao inicializar banco de dados",
                    erro
            );
        }
    }
}
